-- =============================================================================
-- ValetStand — buildable garment stand (The Parasites, UE4SS Lua)
--
-- The pak ships three Blueprints (ue/TheParasites/Scripts/valetstand_assets.py): BP_ValetStand (the BuildingBase ghost with
-- 14 resource parts), BP_ValetStandStation (a BP_MPCraftingStation child: the finished, interactive stand) and
-- BP_ValetStandWidget (its panel: one JSIContainer per garment slot). This script supplies the two pieces of logic a
-- Blueprint child cannot carry when it is built from Python (no graph authoring):
--   1. ghost -> station swap: the game's BP_Small_Box does this in its own event graph (tick until built, spawn
--      SpawnGoodBuilding at its transform, destroy itself). Here: post-hook on BuildingBase_C:BuiltFinished for our class.
--   2. panel slot registration: BP_JigMultiplayer.SetupInventoryWidget asks the panel for GetListOfContainers (an interface
--      function our widget cannot implement) and registers each JSIContainer with AddJSIContainer in ContainersSettings
--      order, then calls SetupWidgetCleanupTimer(). Here: pre-hook on SetupWidgetCleanupTimer (no parameters: a Lua hook on
--      SetupInventoryWidget itself never fired, its ST_FragmentMemory out param defeats UE4SS's callback marshalling) for the
--      station's component, registering the slots from slots.lua (generated by valetstand_assets.py from the same table
--      that wrote ContainersSettings). AddJSIContainer is AddUnique, so the cleanup timer's own call is harmless.
--   3. garments on the stand (dress.lua): each slotted item shown with its worn skeletal mesh in bind pose.
--   4. the panel's Undress and Dress buttons (wardrobe.lua).
-- UE4SS LoadAsset is AssetRegistry-only (docs/build-system.md §10): a brand-new package is not in the cooked registry, so
-- classes are loaded by asking the live AssetRegistry to scan /Game/Mods/ValetStand first (route 3, proven 2026-11-06).
--
-- The stand is built from the notebook: Build tab, page 5 (notebook.lua).
--
-- Console (F10), for debugging:
--   vs load            load the ghost class, report which route worked
--   vs yaw [deg]       rotate the ghost's parts to find the yaw to bake into the asset
--   vs swap            replace the nearest FINISHED ghost by the station now (stands built before this script existed)
--   vs state           every ghost (brush/blocked/under-construction, durability, parts) and station (containers, HP)
--   vs dress           re-dress every station now and list each slot's item and whether it is shown (dress.lua; also polled)
-- =============================================================================
if not require("game_version").supported("ValetStand", { "0.1.6.0.2.5" }) then return end

local UEHelpers = require("UEHelpers")
local SLOTS = require("slots")
local Dress = require("dress")   -- step 4: the slotted garments shown on the stand
local Notebook = require("notebook")   -- the stand's entry in the notebook's Build tab
local Wardrobe = require("wardrobe")   -- the panel's Undress and Dress buttons
local Defer = require("defer")         -- work that must not run inside a hook

local MOD_DIR = "/Game/Mods/ValetStand"
local GHOST_CLASS = MOD_DIR .. "/BP_ValetStand.BP_ValetStand_C"
local STATION_CLASS = MOD_DIR .. "/BP_ValetStandStation.BP_ValetStandStation_C"
local BUILDING_BASE = "/Game/BuildingSystem/Blueprints/BuildingBase.BuildingBase_C"
local JIG_MP = "/Game/JigSInventory/Jigsaw/Components/BP_JigMultiplayer.BP_JigMultiplayer_C"
local SWAP_DELAY_MS = 250   -- let BuiltFinished's own graph (durability, build effect) finish before the ghost is destroyed

local function log(msg) print("[ValetStand] " .. tostring(msg) .. "\n") end

local function isValidObj(o)
    if o == nil or type(o) ~= "userdata" then return false end
    local v = false
    pcall(function() v = o:IsValid() end)
    return v
end

local function fullName(o)
    local s = "?"
    pcall(function() s = o:GetFullName() end)
    return s
end

local function className(o)
    local n = "?"
    pcall(function() n = o:GetClass():GetFName():ToString() end)
    return n
end

-- --- loading our classes ----------------------------------------------------------------
local function tryLoadAsset(path)
    local ok, res, found, loaded = pcall(LoadAsset, path)
    if not ok then return nil, "LoadAsset error: " .. tostring(res) end
    if isValidObj(res) then return res, string.format("found=%s loaded=%s", tostring(found), tostring(loaded)) end
    return nil, string.format("nothing (found=%s loaded=%s)", tostring(found), tostring(loaded))
end

-- make the live AssetRegistry scan the mod folder (what DLC/pak mounting does), then LoadAsset sees the package
local function scanRegistry(out)
    local candidates = {}
    pcall(function() for _, o in ipairs(FindAllOf("AssetRegistryImpl") or {}) do table.insert(candidates, o) end end)
    pcall(function() table.insert(candidates, StaticFindObject("/Script/AssetRegistry.Default__AssetRegistryImpl")) end)
    local any = false
    for _, reg in ipairs(candidates) do
        if isValidObj(reg) then
            local ok, err = pcall(function() reg:ScanPathsSynchronous({ MOD_DIR }, true, false) end)
            out("registry: " .. fullName(reg) .. " ScanPathsSynchronous -> " .. tostring(ok) .. (ok and "" or (" " .. tostring(err))))
            any = any or ok
        end
    end
    if not any then out("registry: no usable AssetRegistry object") end
    return any
end

local function loadClass(path, out)
    local cls = StaticFindObject(path)
    if isValidObj(cls) then out("route 1 StaticFindObject: " .. fullName(cls)) return cls end
    local res, why = tryLoadAsset(path)
    if res then out("route 2 LoadAsset: " .. fullName(res) .. " (" .. why .. ")") return res end
    out("route 2 LoadAsset: " .. why)
    if scanRegistry(out) then
        res, why = tryLoadAsset(path)
        if res then out("route 3 scan+LoadAsset: " .. fullName(res) .. " (" .. why .. ")") return res end
        out("route 3 scan+LoadAsset: " .. why)
    end
    out(path .. " NOT loadable (is zzz_ValetStand_P.pak in Paks? game restarted?)")
    return nil
end

-- --- player / brush ------------------------------------------------------------------------
local function getPawn()
    local pawn = nil
    pcall(function()
        local pc = UEHelpers.GetPlayerController()
        if pc and pc:IsValid() then pawn = pc.Pawn end
    end)
    return isValidObj(pawn) and pawn or nil
end

local function getBuildComponent(pawn)
    local comp = nil
    pcall(function() comp = pawn.ABS_PlayerComponent end)
    if isValidObj(comp) then return comp end
    pcall(function()
        local cls = StaticFindObject("/Game/BuildingSystem/Blueprints/Components/ABS_PlayerComponent.ABS_PlayerComponent_C")
        if isValidObj(cls) then comp = pawn:GetComponentByClass(cls) end
    end)
    return isValidObj(comp) and comp or nil
end

local BUILD_OVERLAY = 18   -- E_TP_OverlayState while placing a building

-- BuildingBase blocks placement on any non-landscape actor its ghost overlaps (a built floor is one), and its default Box/Box1 are
-- 64 cm cubes centred on the base, half below the floor. Every game building resizes Box1 to sit just above the floor and turns Box
-- off; do the same (proven in game: red over BP_BC_Floor_2x2, green after). Done here, not as an inherited-component override in the
-- asset, because the placeholder BuildingBase declares no SCS nodes to override.
local PLACEMENT_BOX = { loc = { X = 0, Y = 0, Z = 86.5 }, scale = { X = 0.8, Y = 0.8, Z = 2.61 } }   -- 3 cm to 170 cm, 26 cm half width

local function fitPlacementBoxes(brush, out)
    local ok, err = pcall(function()
        brush.Box:SetGenerateOverlapEvents(false)
        brush.Box:SetCollisionEnabled(0)
        brush.Box1:K2_SetRelativeLocation(PLACEMENT_BOX.loc, false, {}, false)
        brush.Box1:SetRelativeScale3D(PLACEMENT_BOX.scale)
    end)
    if not ok then out("placement boxes not set: " .. tostring(err)) end
end

local function place(out)
    local pawn = getPawn()
    if not pawn then out("no player pawn") return end
    local comp = getBuildComponent(pawn)
    if not comp then out("no ABS_PlayerComponent on the pawn") return end
    local cls = loadClass(GHOST_CLASS, out)
    if not cls then return end
    -- As the game's own build entry points do (Base_Notepap.Building, JigContextMenuComp): left click only commits in overlay state 18,
    -- otherwise it attacks. ExitConstructionMode puts the overlay back to 0. SetBrushClass calls SetBuildingMode itself.
    local ok, err = pcall(function() pawn:BPI_Set_OverlayState(BUILD_OVERLAY) end)
    out("BPI_Set_OverlayState(" .. BUILD_OVERLAY .. ") -> " .. tostring(ok) .. (ok and "" or (" " .. tostring(err))))
    -- false: backing out returns to the open notebook, as for the game's own entries
    ok, err = pcall(function() comp:SetBrushClass(cls, true, false) end)
    out("SetBrushClass -> " .. tostring(ok) .. (ok and "" or (" " .. tostring(err))))
    local brush = nil
    pcall(function() brush = comp.TmpCurrentActorBuilding end)
    if isValidObj(brush) then fitPlacementBoxes(brush, out) else out("no brush to fit placement boxes on") end
    local r = {}   -- UE4SS: out parameters come back in a table passed in their place
    pcall(function() comp:IsBuilding(r) end)
    pcall(function() out("overlay=" .. tostring(pawn.OverlayState) .. " IsBuilding()=" .. tostring(r.IsBuilding) .. " brush=" .. tostring(comp.TmpCurrentActorBuilding)) end)
end

-- The notebook entry was clicked: what Base_Notepap.Building does for its own entries, leaving the open notebook for the world view.
local function buildFromBook()
    local pawn = getPawn()
    if not pawn then log("book: no player pawn") return end
    if pawn.OverlayState == 27 then return end   -- the game refuses to start a build in this state too
    place(log)
    local pc = pawn.Controller
    local steps = {
        { "view", function() pawn:BPI_Set_ViewMode(0) end },
        { "input", function() StaticFindObject("/Script/UMG.Default__WidgetBlueprintLibrary"):SetInputMode_GameOnly(pc, false) end },
        { "cursor", function() pc.bShowMouseCursor = false end },
        { "blur", function() pawn:PlayBlur(false, 15, true, 1.3, 31) end },
        { "camera", function() pawn.LockCamera = false end },
        { "black screen", function() pawn:UpdateBlackScreen(false, false, nil) end },
        { "focus", function() pawn.FocusCameraOnTarget:Stop() end },
        { "look", function() pc:ResetIgnoreLookInput() end },
        { "head", function() pawn:HideHead(false, true) end },
    }
    for _, s in ipairs(steps) do
        local ok, err = pcall(s[2])
        if not ok then log("book: " .. s[1] .. " failed: " .. tostring(err)) end
    end
end

-- the ABS_MeshComponent parts owned by `actor` (K2_GetComponentsByClass returns nothing through UE4SS)
local function partsOf(actor)
    local list, me = {}, fullName(actor)
    pcall(function()
        for _, c in ipairs(FindAllOf("ABS_MeshComponent_C") or {}) do
            if isValidObj(c) then
                local owner = nil
                pcall(function() owner = c:GetOuter() end)
                if owner and fullName(owner) == me then table.insert(list, c) end
            end
        end
    end)
    return list
end

-- the ghost the brush is showing (component var first, then our class's only instance)
local function currentBrush(comp)
    local b = nil
    pcall(function() b = comp.TmpCurrentActorBuilding end)
    if isValidObj(b) then return b end
    pcall(function()
        for _, a in ipairs(FindAllOf("BP_ValetStand_C") or {}) do if isValidObj(a) then b = a end end
    end)
    return isValidObj(b) and b or nil
end

-- rotate every part of the current ghost about the actor's Z by `deg` (to find the yaw to bake into the asset)
local function yawParts(deg, out)
    local pawn = getPawn(); if not pawn then out("no pawn") return end
    local comp = getBuildComponent(pawn); if not comp then out("no ABS_PlayerComponent") return end
    local b = currentBrush(comp); if not b then out("no ghost found") return end
    local r = math.rad(deg); local c, s = math.cos(r), math.sin(r); local n = 0
    for _, m in ipairs(partsOf(b)) do
        pcall(function()
            local l = m.RelativeLocation; local q = m.RelativeRotation
            local x, y = l.X, l.Y
            m:K2_SetRelativeLocationAndRotation({ X = x * c - y * s, Y = x * s + y * c, Z = l.Z },
                                                { Pitch = q.Pitch, Yaw = q.Yaw + deg, Roll = q.Roll }, false, {}, false)
            n = n + 1
        end)
    end
    out("yawed " .. n .. " parts by " .. deg .. " deg (bake the total into valetstand_assets.py STAND_YAW)")
end

-- --- ghost -> station -------------------------------------------------------------------------
-- spawn BP_ValetStandStation at the ghost's transform and destroy the ghost (BP_Small_Box's own graph does exactly this)
local function swapToStation(ghost, out)
    if not isValidObj(ghost) then out("swap: ghost gone") return end
    local cls = loadClass(STATION_CLASS, out)
    if not cls then return end
    local loc, rot = nil, nil
    pcall(function() loc = ghost:K2_GetActorLocation(); rot = ghost:K2_GetActorRotation() end)
    if not loc then out("swap: no ghost transform") return end
    local station = nil
    local ok, err = pcall(function()
        station = UEHelpers.GetWorld():SpawnActor(cls, { X = loc.X, Y = loc.Y, Z = loc.Z }, { Pitch = rot.Pitch, Yaw = rot.Yaw, Roll = rot.Roll })
    end)
    if not ok or not isValidObj(station) then out("swap: SpawnActor failed " .. tostring(err)) return end
    out("swap: " .. fullName(station) .. " at " .. string.format("%.0f %.0f %.0f yaw %.0f", loc.X, loc.Y, loc.Z, rot.Yaw))
    pcall(function() ghost:K2_DestroyActor() end)
end

-- 'vs swap': the nearest finished ghost (built before the hook existed, e.g. the one already in the save)
local function swapNearest(out)
    local pawn = getPawn(); if not pawn then out("no pawn") return end
    local best, bestD = nil, 1e9
    for _, b in ipairs(FindAllOf("BP_ValetStand_C") or {}) do
        if isValidObj(b) then
            local finished, d = false, 1e9
            pcall(function() finished = (not b.UnderConstruction) and (not b.BrushMode) end)
            if finished then pcall(function() d = b:GetDistanceTo(pawn) end) end
            if finished and d < bestD then best, bestD = b, d end
        end
    end
    if not best then out("no finished ghost in the world") return end
    swapToStation(best, out)
end

-- --- station panel: register the slots the way GetListOfContainers would --------------------
local function registerPanelSlots(comp, out)
    local w = nil
    pcall(function() w = comp.InventoryWidgetRef end)
    if not isValidObj(w) then out("panel: no InventoryWidgetRef on the station component") return end
    local n = 0
    for _, name in ipairs(SLOTS) do
        local c = nil
        pcall(function() c = w[name] end)
        if isValidObj(c) then
            local ok, err = pcall(function() comp:AddJSIContainer(c) end)   -- Array_AddUnique inside: re-opening the panel is harmless
            if ok then n = n + 1 else out("panel: AddJSIContainer(" .. name .. ") " .. tostring(err)) end
        else
            out("panel: slot widget missing: " .. name)
        end
    end
    out("panel: registered " .. n .. "/" .. #SLOTS .. " slots on " .. fullName(comp))
end

-- --- hooks ----------------------------------------------------------------------------------
local hooked = {}
local function hook(path, fn)   -- pre-callback: BuiltFinished's work is deferred anyway, SetupWidgetCleanupTimer needs no ordering
    if hooked[path] then return true end
    if not isValidObj(StaticFindObject(path:match("^(.-):"))) then return false end
    local ok, err = pcall(RegisterHook, path, function(Context, ...)
        local ok2, err2 = pcall(fn, Context, { ... })
        if not ok2 then log("hook " .. path:match("[^:]+$") .. " error: " .. tostring(err2)) end
    end)
    if ok then hooked[path] = true log("hooked " .. path:match("[^:]+$")) else log("hook failed " .. path .. ": " .. tostring(err)) end
    return ok
end

local function installHooks()
    local a = hook(BUILDING_BASE .. ":BuiltFinished", function(Context)
        local ghost = Context:get()
        if className(ghost) ~= "BP_ValetStand_C" then return end
        log("BuiltFinished on " .. fullName(ghost) .. " -> station in " .. SWAP_DELAY_MS .. " ms")
        Defer.run(function() swapToStation(ghost, log) end, SWAP_DELAY_MS)
    end)
    local b = hook(JIG_MP .. ":SetupWidgetCleanupTimer", function(Context)
        local comp = Context:get()
        local owner, widget = nil, nil
        pcall(function() owner = comp:GetOwner(); widget = comp.InventoryWidgetRef end)
        if className(owner) ~= "BP_ValetStandStation_C" or className(widget) ~= "BP_ValetStandWidget_C" then return end
        registerPanelSlots(comp, log)
    end)
    return a and b
end

local polls = 0
local function hookPoll()
    Defer.run(function()
        polls = polls + 1
        -- A call right after RegisterHook has thrown (string.match: "number expected, got function", once, 2026-11-09). Unprotected, that ended this
        -- loop with SetupWidgetCleanupTimer unhooked and the panel's slots unregistered. A hook already made is remembered, so a retry is cheap.
        local ok, done = pcall(installHooks)
        if not ok then log("hook install failed, retrying: " .. tostring(done)) end
        if not (ok and done) and polls < 300 then Defer.run(hookPoll, 2000) end   -- the classes exist once a level with buildings is up
    end)
end
Defer.start()
hookPoll()

-- --- state -----------------------------------------------------------------------------------
local function state(out)
    local pawn = getPawn()
    local n = 0
    for _, b in ipairs(FindAllOf("BP_ValetStand_C") or {}) do
        if isValidObj(b) then
            n = n + 1
            local d = -1
            if pawn then pcall(function() d = b:GetDistanceTo(pawn) end) end
            local dur = {}
            pcall(function() b:GetDurability(dur) end)
            local st = ""
            pcall(function() st = string.format("brush=%s blocked=%s underConstruction=%s", tostring(b.BrushMode), tostring(b.IsBloqued), tostring(b.UnderConstruction)) end)
            out(string.format("ghost #%d %s at %.0f uu %s durability cur=%s count=%s destroy=%s", n, b:GetFName():ToString(), d, st,
                tostring(dur.CurrentDurability), tostring(dur.CountDurability), tostring(dur.DestroyDurability)))
            local ps = partsOf(b)
            for _, c in ipairs(ps) do
                local rt, cur, tot, hollow, mesh = "?", "?", "?", "?", "?"
                pcall(function() rt = tostring(c.ResourceType) end)
                pcall(function() cur = tostring(c.CurrentAmount) end)
                pcall(function() tot = tostring(c.TotalAmount) end)
                pcall(function() hollow = tostring(c.IsHollow) end)
                pcall(function() mesh = c.StaticMesh:GetFName():ToString() end)
                out(string.format("   %-16s type=%s %s/%s hollow=%s mesh=%s", c:GetFName():ToString(), rt, cur, tot, hollow, mesh))
            end
            out("   " .. #ps .. " parts")
        end
    end
    local m = 0
    for _, s in ipairs(FindAllOf("BP_ValetStandStation_C") or {}) do
        if isValidObj(s) then
            m = m + 1
            local d, hp, interact, containers, widget = -1, "?", "?", "?", "?"
            if pawn then pcall(function() d = s:GetDistanceTo(pawn) end) end
            pcall(function() hp = tostring(s.HP) end)
            pcall(function() interact = tostring(s.Interact) end)
            pcall(function() containers = tostring(s.BP_JigMultiplayer.MainContainersIDs:GetArrayNum()) end)
            pcall(function() widget = fullName(s.BP_JigMultiplayer.InventoryWidgetRef) end)
            out(string.format("station #%d %s at %.0f uu HP=%s Interact=%s containers=%s panel=%s", m, s:GetFName():ToString(), d, hp, interact, containers, widget))
        end
    end
    if n + m == 0 then out("no BP_ValetStand_C / BP_ValetStandStation_C in the world") end
end

RegisterConsoleCommandHandler("vs", function(_, params)
    local out = function(s) log(s) end
    local sub = params[1] or "help"
    if sub == "load" then loadClass(GHOST_CLASS, out)
    elseif sub == "state" then state(out)
    elseif sub == "swap" then swapNearest(out)
    elseif sub == "yaw" then yawParts(tonumber(params[2] or "90") or 90, out)
    elseif sub == "dress" then Dress.dressAll(out); Dress.report(out)
    else out("vs load | vs yaw [deg] | vs swap | vs state | vs dress") end
    return true
end)
Dress.start()
Notebook.start(buildFromBook, function(path) return loadClass(path, function() end) end)
Wardrobe.start()
log("loaded (vs load/yaw/swap/state/dress; " .. #SLOTS .. " panel slots)")
